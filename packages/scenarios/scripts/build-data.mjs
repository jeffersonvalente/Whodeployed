#!/usr/bin/env node
// T2.18 — data bundle for the UI (ADR-014 §4, FASE-2 PR-19 "the UI does not know YAML", DET).
//
// Runs after `tsc` in `pnpm build`. Loads every scenario YAML with this package's own loader
// (dist/node.js, with the EngineRuntime built from the engine's public entry, a devDependency:
// ADR-014 §1.1) and writes:
//   dist/data.js    `export const bundle = {...}`: already-parsed plain data, no imports at all,
//                   so the "./data" entry never pulls `yaml` or the loader into the browser.
//   dist/data.d.ts  `bundle` typed as ScenarioBundle (from "./index.js").
// `campaign` holds the `NN-*` scenarios and `testIncidents` the `test-*` ones, each ordered by id
// (code-unit order). Output is a pure function of the YAML files: same input => byte-identical
// files (DET). Any invalid YAML => message of the loader on stderr and exit code 1.
//
// Usage: node scripts/build-data.mjs [--scenarios <dir>] [--out <dir>]
//   defaults: <package>/scenarios and <package>/dist (options exist for the tests' fixtures).
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { accumulatedImpact, createSimulation, defaultShop, resolveFaults } from '@whodeployed/engine'

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const CAMPAIGN_ID = /^[0-9]{2}-[a-z0-9-]+$/
const TEST_ID = /^test-[a-z0-9-]+$/

/** Code-unit order of ids (locale-independent, so the output does not depend on the machine). */
const byId = (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)

async function main() {
  const { values } = parseArgs({
    options: {
      scenarios: { type: 'string', default: join(packageDir, 'scenarios') },
      out: { type: 'string', default: join(packageDir, 'dist') },
    },
    strict: true,
  })
  const scenariosDir = resolve(values.scenarios)
  const outDir = resolve(values.out)

  // The compiled loader (tsc ran first in `build`). Imported here, at build time only.
  const { loadScenarioDir } = await import(join(packageDir, 'dist', 'node.js'))
  const engine = { resolveFaults, createSimulation, accumulatedImpact, systems: { 'default-shop': defaultShop } }

  const scenarios = loadScenarioDir(scenariosDir, engine)

  const campaign = []
  const testIncidents = []
  for (const scenario of scenarios) {
    if (scenario.testIncident && TEST_ID.test(scenario.id)) testIncidents.push(scenario)
    else if (!scenario.testIncident && CAMPAIGN_ID.test(scenario.id)) campaign.push(scenario)
    else throw new Error(`build-data: scenario '${scenario.id}' is neither a campaign (NN-*) nor a test (test-*) incident`)
  }
  campaign.sort(byId)
  testIncidents.sort(byId)

  const bundle = { campaign, testIncidents }
  const js =
    '// Generated by scripts/build-data.mjs from scenarios/*.yaml (ADR-014 §4). Do not edit.\n' +
    '// Already-parsed data: this module imports nothing (FASE-2 PR-19, "the UI does not know YAML").\n' +
    `export const bundle = ${JSON.stringify(bundle, null, 2)};\n`
  const dts =
    '// Generated by scripts/build-data.mjs (ADR-014 §4). Do not edit.\n' +
    "import type { ScenarioBundle } from './index.js';\n" +
    'export declare const bundle: ScenarioBundle;\n'

  mkdirSync(outDir, { recursive: true })
  writeFileSync(join(outDir, 'data.js'), js)
  writeFileSync(join(outDir, 'data.d.ts'), dts)
  process.stdout.write(
    `build-data: ${campaign.length} campaign scenario(s), ${testIncidents.length} test incident(s) -> ${join(outDir, 'data.js')}\n`,
  )
}

main().catch((error) => {
  // ScenarioError.message already names file, field and reason (CN-4); print it as is.
  const message = error instanceof Error && error.name === 'ScenarioError' ? error.message : error instanceof Error ? (error.stack ?? error.message) : String(error)
  process.stderr.write(`build-data: ${message}\n`)
  process.exitCode = 1
})
