/**
 * T1.27 — telemetry fixtures (PRD D-3, ADR-005 "Fixtures"; DET).
 *
 * fixtures/ holds exactly 7 NDJSON files (baseline + the 6 kinds; fixtures/answers/ is a
 * subdirectory and does not count, PRD Emenda 1). Each one is the output of the CLI command that
 * scripts/gen-fixtures.mjs lists for it (`whodeployed-engine simulate --seed fixture --ticks 60
 * [--fault <kind>]`). This test reads that command table from the script, regenerates every
 * fixture in memory through the CLI pipeline (parseCliArgs -> buildWorld -> resolveFaults ->
 * simulate -> toNdjson, as src/cli/main.ts does) and compares byte for byte. One fixture is also
 * regenerated by the real CLI in a separate process, so the in-memory path is the CLI's.
 *
 * When the engine output changes on purpose, regenerate with
 *   corepack pnpm --filter ./packages/engine fixtures
 * and explain the diff in the PR (ADR-005 "Consequências").
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { parseCliArgs } from '../src/cli/args.js'
import { faultKinds } from '../src/faults/catalog.js'
import { resolveFaults } from '../src/faults/resolve.js'
import { toNdjson } from '../src/sim/serialize.js'
import { simulate } from '../src/sim/simulation.js'
import { buildWorld } from '../src/world/build.js'
import { defaultShop } from '../src/world/default-shop.js'

const pkgDir = fileURLToPath(new URL('..', import.meta.url))
const fixturesDir = join(pkgDir, 'fixtures')
const script = join(pkgDir, 'scripts', 'gen-fixtures.mjs')
const mainTs = join(pkgDir, 'src', 'cli', 'main.ts')

/** ADR-005 Emenda 2 size budget per 60-tick NDJSON: 3 MiB. */
const MAX_BYTES = 3_145_728
const TICKS = 60

const sha = (text: string) => createHash('sha256').update(text, 'utf8').digest('hex')

interface FixtureEntry {
  file: string
  args: string[]
}

function commandTable(): { bin: string; fixtures: FixtureEntry[] } {
  const r = spawnSync(process.execPath, [script, '--list'], { cwd: pkgDir, encoding: 'utf8' })
  expect(r.stderr).toBe('')
  expect(r.status).toBe(0)
  return JSON.parse(r.stdout) as { bin: string; fixtures: FixtureEntry[] }
}

/** The CLI `simulate` pipeline of src/cli/main.ts, in memory. */
function regenerate(args: readonly string[]): string {
  const command = parseCliArgs(args)
  if (command.kind !== 'simulate') throw new Error(`not a simulate command: ${args.join(' ')}`)
  const faults = resolveFaults(command.faults, buildWorld(defaultShop, command.seed))
  return toNdjson(simulate({ system: defaultShop, seed: command.seed, faults }, command.ticks))
}

const TABLE = commandTable()
const EXPECTED_FILES = ['baseline.ndjson', ...faultKinds.map((k) => `${k}.ndjson`)]

describe('D-3 — the command table of scripts/gen-fixtures.mjs follows ADR-005', () => {
  it('lists the bin and 7 fixtures: baseline + the 6 kinds, in ADR-004 order', () => {
    expect(TABLE.bin).toBe('whodeployed-engine')
    expect(TABLE.fixtures.map((f) => f.file)).toEqual(EXPECTED_FILES)
  })

  it('each command is `simulate --seed fixture --ticks 60 [--fault <kind>]` with catalog defaults', () => {
    const base = ['simulate', '--seed', 'fixture', '--ticks', String(TICKS)]
    expect(TABLE.fixtures[0]!.args).toEqual(base)
    faultKinds.forEach((kind, i) => expect(TABLE.fixtures[i + 1]!.args).toEqual([...base, '--fault', kind]))
  })

  it('an unknown fixture name is a usage error (exit 2, nothing written)', () => {
    const r = spawnSync(process.execPath, [script, 'nope'], { cwd: pkgDir, encoding: 'utf8' })
    expect(r.status).toBe(2)
    expect(r.stdout).toBe('')
    expect(r.stderr).toMatch(/unknown fixture.*nope.*baseline/)
  })
})

describe('D-3 — fixtures/*.ndjson', () => {
  it('`ls fixtures/*.ndjson` = exactly the 7 files (subdirectories such as answers/ do not count)', () => {
    const ndjson = readdirSync(fixturesDir)
      .filter((name) => name.endsWith('.ndjson') && statSync(join(fixturesDir, name)).isFile())
      .sort()
    expect(ndjson).toEqual([...EXPECTED_FILES].sort())
  })

  it.each(EXPECTED_FILES)('%s is <= 3 MiB and covers ticks 0..59', (file) => {
    const path = join(fixturesDir, file)
    expect(existsSync(path), `${file} is missing: run the fixtures script`).toBe(true)
    expect(statSync(path).size).toBeLessThanOrEqual(MAX_BYTES)
    const ticks = new Set<number>()
    for (const line of readFileSync(path, 'utf8').trimEnd().split('\n')) {
      const tick = (JSON.parse(line) as { tick: unknown }).tick
      expect(Number.isInteger(tick)).toBe(true)
      ticks.add(tick as number)
    }
    expect([...ticks].sort((a, b) => a - b)).toEqual(Array.from({ length: TICKS }, (_, i) => i))
  })
})

describe('D-3 / DET — regenerating in memory gives the committed bytes', () => {
  it.each(TABLE.fixtures.map((f) => [f.file, f.args] as const))('%s', (file, args) => {
    const path = join(fixturesDir, file)
    expect(existsSync(path), `${file} is missing: run the fixtures script`).toBe(true)
    const committed = readFileSync(path, 'utf8')
    const fresh = regenerate(args)
    // Hash first, so a mismatch reports two short strings instead of a multi-MB diff.
    expect(sha(fresh), `${file} differs from a fresh run: regenerate with the fixtures script`).toBe(sha(committed))
    expect(fresh === committed).toBe(true)
  })

  it(
    'the real CLI, in a separate process, prints the committed baseline byte for byte',
    () => {
      const entry = TABLE.fixtures[0]!
      const r = spawnSync(process.execPath, ['--import', 'tsx', mainTs, ...entry.args], {
        cwd: pkgDir,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
        maxBuffer: 512 * 1024 * 1024,
      })
      expect(r.stderr).toBe('')
      expect(r.status).toBe(0)
      expect(sha(r.stdout)).toBe(sha(readFileSync(join(fixturesDir, entry.file), 'utf8')))
    },
    60_000,
  )
})
